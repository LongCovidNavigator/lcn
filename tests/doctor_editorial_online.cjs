const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('scripts/arzt_detail_konzept.js','utf8');
const researchFunctions=source.slice(source.indexOf('  function isOnlinePostalAddress('),source.indexOf('  function dataStatus()'));
const onlineFunction=source.slice(source.indexOf('  function onlineAppointments()'),source.indexOf('  function travelEstimate()'));
const entity={ersttermin_video:'ja',folgetermin_video:'ja',ersttermin_vor_ort:'nein',folgetermin_vor_ort:'nein'};
const sandbox={doctorId:673,state:{data:{item:{},research:{entity}}},window:{LCNOnline:{fromQuestions:()=>({first:false,follow:false})}}};
vm.createContext(sandbox);
vm.runInContext(researchFunctions+onlineFunction,sandbox);
assert.equal(sandbox.researchedRemoteAccess().complete,false,'Raw editorial fields cannot bypass community answers');
assert.equal(sandbox.researchedRemoteNotice(),'');
assert.equal(sandbox.onlineAppointments().complete,false);
sandbox.window.LCNOnline.fromQuestions=()=>({first:true,follow:true});
assert.equal(sandbox.onlineAppointments().complete,true,'Community-confirmed access still works');
assert.equal(sandbox.onlineAppointments().source,'community');
sandbox.state.data.research.online_only_verified=true;
sandbox.window.LCNOnline.fromQuestions=()=>({first:false,follow:false});
assert.equal(sandbox.researchedRemoteAccess().exclusive,true);
assert.equal(sandbox.onlineAppointments().complete,true,'Verified online-only exception applies without community votes');
assert(sandbox.researchedRemoteNotice().includes('Nur Online-Termine möglich'));
assert(!source.includes('<div class="block-content">${researchedRemoteNotice()}<div class="appointment-table"'));
console.log('PASS: editorial access requires verified exception; other profiles depend on community; no notice in appointment input.');
